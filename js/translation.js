let currentLanguage = localStorage.getItem("aura_language") || "en";

function translateAllElements() {
  const dictionary = AURA_TRANSLATIONS[currentLanguage];
  if (!dictionary) return;

  document.querySelectorAll("[data-translate]").forEach(el => {
    const key = el.getAttribute("data-translate");
    if (dictionary[key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.setAttribute("placeholder", dictionary[key]);
      } else {
        el.innerText = dictionary[key];
      }
    }
  });
}

function setLanguage(lang) {
  if (AURA_TRANSLATIONS[lang]) {
    currentLanguage = lang;
    localStorage.setItem("aura_language", lang);
    translateAllElements();
    
    // Sync language selector value
    const langSelect = document.getElementById("header-language-select");
    if (langSelect) {
      langSelect.value = lang;
    }
  }
}

// Auto-run on DOM loaded
document.addEventListener("DOMContentLoaded", () => {
  translateAllElements();
  
  // Setup dropdown listener if exists
  const langSelect = document.getElementById("header-language-select");
  if (langSelect) {
    langSelect.value = currentLanguage;
    langSelect.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  }
});

// Export to window
window.AuraTranslator = {
  setLanguage,
  translateAllElements,
  getCurrentLanguage: () => currentLanguage
};
